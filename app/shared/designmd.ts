// Phase 102: DESIGN.md, the design system written for an agent working in a project: colour tokens of
// the light and dark themes, the contrast each pair keeps, the shapes, type and motion. Made from the
// same sources the app uses, so it is regenerated, never edited by hand.

export type Palette = { id: string; name: string; scheme: 'light' | 'dark'; c: Record<string, string> }
export type Rule = { fg: string; bg: string; min: number; use: string }

const ROLE: Record<string, string> = {
  bg: 'page background', surface: 'cards, sheets', raised: 'fields, raised rows', hover: 'hover fill', sunken: 'wells, code',
  text: 'body text', muted: 'secondary text', faint: 'hints, mono labels (large or bold only)', accent: 'the one thing to do, current item',
  accentHover: 'accent on hover', deep: 'accent ink, pressed', glow: 'soft accent light', onAccent: 'text on accent',
  green: 'success with its label', red: 'danger with its label', gold: 'warning with its label', blue: 'info with its label',
}
const VAR = (k: string) => `--${k.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`)}`

export function designMd(themes: Palette[], rules: Rule[], ratio: (a: string, b: string) => number): string {
  const keys = Object.keys(themes[0]?.c ?? {})
  const head = ['Token', 'CSS variable', 'Role', ...themes.map((t) => t.name)]
  const rows = keys.map((k) => [`\`${k}\``, `\`${VAR(k)}\``, ROLE[k] ?? '', ...themes.map((t) => `\`${t.c[k]}\``)])
  const table = (h: string[], r: string[][]) => [`| ${h.join(' | ')} |`, `| ${h.map(() => '---').join(' | ')} |`, ...r.map((x) => `| ${x.join(' | ')} |`)].join('\n')
  const contrast = rules.map((r) => [`${r.fg} on ${r.bg}`, r.use, `${r.min}:1`, ...themes.map((t) => `${ratio(t.c[r.fg]!, t.c[r.bg]!).toFixed(2)}:1`)])
  return `# DESIGN.md

Generated by SuperTokenMan from its design system. Do not edit by hand: export it again after a change.

Style: Constructivist and Swiss. Flat colour, hard edges, a grid, uppercase mono labels, one warm accent.

## Colour tokens

Use the CSS variables, never a hex value in a component. Each theme sets every token.

${table(head, rows)}

## Contrast

WCAG 2.2: 4.5:1 for text, 3:1 for large text, icons and lines. Every pair below is kept in every theme.

${table(['Pair', 'Used for', 'Minimum', ...themes.map((t) => t.name)], contrast)}

## Shape

- Corners are cut at 45°, never rounded: \`clip-path: polygon(0 0, calc(100% - 10px) 0, 100% 10px, 100% 100%, 0 100%)\` (10 to 12 px).
- 1 px borders in \`--border-strong\`; focus is an inset accent bar (3 px on the left), never an outer ring.
- The accent marks one thing per view: the main action or the current item.
- Status colours always come with a word or an icon, never colour alone.

## Type

- Text: the system sans at 13 to 14 px, weight 400; titles 600.
- Labels: mono, 10 to 11 px, uppercase, letter spacing 1 px, in \`--faint\`.
- Numbers: tabular figures.

## Icons

- 16 px box, 1.5 px stroke in \`currentColor\`, round caps; straight lines at multiples of 45°. No fixed colours.

## Motion

- Short and printed: 120 to 420 ms, ease \`--print\`. Moves: stamp (scale down into place), diagonal entry along 45°, split-flap for changing numbers.
- Under \`prefers-reduced-motion\`, nothing travels: things only fade.

## Content

- English, plain words, no emoji. Say what happened and what to do next.
`
}
